// Scans /public and writes lib/assetManifest.ts so the preloader always knows
// every photo and song. Runs automatically before `npm run dev` / `npm run build`,
// so new photos or music you drop into /public are picked up with no code edits.
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const pub = path.join(root, 'public')

const list = (dir, exts) => {
  const full = path.join(pub, dir)
  if (!fs.existsSync(full)) return []
  return fs
    .readdirSync(full, { withFileTypes: true })
    .filter(e => e.isFile() && exts.some(x => e.name.toLowerCase().endsWith(x)))
    .map(e => '/' + (dir ? dir + '/' : '') + e.name)
    .sort()
}

const IMG = ['.webp', '.jpg', '.jpeg', '.png']
const manifest = {
  WALL_THUMBS: list('photos/t', IMG),
  ROOT_IMAGES: list('', IMG),
  PHOTOS: list('photos', IMG),
  MUSIC_FILES: list('music', ['.mp3', '.m4a']),
}

const out =
  '// AUTO-GENERATED by scripts/gen-assets.js — do not edit by hand.\n' +
  Object.entries(manifest)
    .map(([k, v]) => `export const ${k}: string[] = ${JSON.stringify(v, null, 2)}\n`)
    .join('\n')

fs.writeFileSync(path.join(root, 'lib', 'assetManifest.ts'), out)
console.log(
  `[gen-assets] ${manifest.WALL_THUMBS.length} thumbs, ${manifest.PHOTOS.length} photos, ` +
    `${manifest.ROOT_IMAGES.length} root images, ${manifest.MUSIC_FILES.length} songs`
)
